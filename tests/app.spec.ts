import { test, expect } from '@playwright/test';
import path from 'node:path';
test('衣物入库、修改、筛选与刷新保留、删除', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '衣橱', exact: true }).click();
  await page.getByRole('button', { name: '添加衣物' }).click();
  await page.getByLabel('衣物照片', { exact: true }).setInputFiles(path.resolve('public/images/editorial.png'));
  await page.getByLabel('衣物名称').fill('我的测试白衬衫');
  await page.getByRole('button', { name: '保存衣物', exact: true }).click();
  await expect(page.getByText('我的测试白衬衫', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: '衣橱', exact: true }).click();
  await page.getByLabel('搜索衣橱').fill('我的测试');
  await page.getByRole('button', { name: '查看 我的测试白衬衫' }).click();
  await page.getByRole('button', { name: '编辑衣物' }).click();
  await page.getByLabel('衣物名称').fill('改名后的衬衫');
  await page.getByRole('button', { name: '保存衣物', exact: true }).click();
  await page.getByLabel('搜索衣橱').fill('改名后');
  await page.getByRole('button', { name: '查看 改名后的衬衫' }).click();
  await page.getByRole('button', { name: '删除衣物', exact: true }).click();
  await page.getByRole('button', { name: '确认删除' }).click();
  await expect(page.getByText('没有找到衣物')).toBeVisible();
});
test('档案保存、穿搭组合与穿着记录', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '我的档案' }).click();
  await page.getByLabel('昵称').fill('林林');
  await page.getByLabel('身高（cm）').fill('168');
  await page.getByRole('button', { name: '保存档案' }).click();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '穿搭集', exact: true }).click();
  await page.getByRole('button', { name: '新建穿搭' }).click();
  await page.getByLabel('穿搭名称').fill('周一通勤');
  await page.getByRole('checkbox', { name: '云朵白 · 宽松衬衫' }).check();
  await page.getByRole('checkbox', { name: '沙色垂感阔腿裤' }).check();
  await page.getByRole('button', { name: '保存穿搭', exact: true }).click();
  await page.getByRole('button', { name: '查看穿搭 周一通勤' }).click();
  await page.getByRole('button', { name: '今天穿了' }).click();
  await expect(page.getByRole('button', { name: '今日已记录' })).toBeDisabled();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '我的档案' }).click();
  await expect(page.getByLabel('昵称')).toHaveValue('林林');
  await expect(page.getByLabel('身高（cm）')).toHaveValue('168');
});
test('试衣必须明确确认照片上传，取消后不产生结果', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '试衣间', exact: true }).click();
  await page.getByRole('button', { name: '使用示例模特' }).click();
  await page.getByRole('button', { name: '选择 云朵白 · 宽松衬衫' }).click();
  await page.getByRole('button', { name: '生成试衣效果', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '确认上传照片' })).toBeVisible();
  await page.getByRole('button', { name: '暂不上传' }).click();
  await expect(page.getByText('确认上传照片', { exact: true })).not.toBeVisible();
  await expect(page.getByRole('button', { name: '生成试衣效果', exact: true })).toBeVisible();
});
